# Finds the hits in assets/audio/promo-track.m4a and writes src/promo-onsets.js, which the promo
# uses to snap every on-screen entrance onto a real hit in the song.
#   python3 scripts/promo-onsets.py      (needs numpy and ffmpeg)
import subprocess, numpy as np
SR, HOP, WIN = 44100, 128, 2048
pcm = subprocess.run(['ffmpeg', '-v', 'error', '-i', 'assets/audio/promo-track.m4a', '-ac', '1', '-ar', str(SR), '-f', 'f32le', '-'],
                     capture_output=True, check=True).stdout
x = np.frombuffer(pcm, dtype=np.float32)
frames = np.lib.stride_tricks.sliding_window_view(x, WIN)[::HOP] * np.hanning(WIN)
mag = np.log1p(np.abs(np.fft.rfft(frames)) * 10)
flux = np.r_[0, np.maximum(0, np.diff(mag, axis=0)).sum(1)]   # spectral flux
fps = SR / HOP
k = int(0.5 * fps)
f = flux - np.convolve(flux, np.ones(k) / k, 'same')           # remove the local level
f /= f.std()
peaks = [i for i in range(3, len(f) - 4) if f[i] > 1.2 and f[i] == f[i - 3:i + 4].max()]
times = [round(i / fps, 3) for i in peaks]
with open('src/promo-onsets.js', 'w') as fh:
    fh.write('// Generated by scripts/promo-onsets.py from assets/audio/promo-track.m4a. Do not edit.\n')
    fh.write('window.ONSETS = [' + ', '.join(f'{t:g}' for t in times) + '];\n')
print(len(times), 'onsets')

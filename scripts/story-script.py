# Writes STORY-SCRIPT.md: the voiceover script for the "Our story" video with the time each line (and phrase) starts.
#   python3 scripts/story-script.py
# Timings come from src/story-vo.js (the timeline the animation is cut to), plus the hand-checked phrase starts set at the top
# of src/story.js, so the script always matches the render.
import re, json
src = open('src/story-vo.js').read()
clips = [[float(m.group(1)), json.loads(m.group(2))] for m in re.finditer(r'\{ dur: ([\d.]+), chunks: (\[.*?\]) \}', src)]
at = json.loads(re.search(r'VO_AT = (\[.*?\])', src).group(1))
for i, offs in re.findall(r'VO_CLIPS\[(\d+)\]\.chunks\.forEach\(\(c, k\) => \(c\[1\] = (\[.*?\])\[k\]\)\)', open('src/story.js').read()):
    for c, o in zip(clips[int(i)][1], json.loads(offs)): c[1] = o
say = [l['say'] for l in json.load(open('scripts/vo/story.json'))['lines']]
say[19] = 'But the right message, at the right time, brings it right back. A simple "we miss you" beats any ad.'
beats = [
 "Mom waves from her salon. The seven kids pop in as you finish the line.",
 "Banners land on each phrase: 7 KIDS · 1 CHAIR · ZERO SLOW WEEKS.",
 "Food, clothes and care icons pop on each word.",
 "7 PAIRS OF SHOES, then the kids grow on “overnight” (TOO SMALL. AGAIN.).",
 "You appear by the regulars board with a “?” bubble.",
 "Photos drift off the board one by one.",
 "The empty chair. The calendar flips to April and a tumbleweed rolls by.",
 "The dust bunny pops up, “Booked 10:00”, on “dust”.",
 "Coins float out of the family money jar.",
 "Subscription cards stack up. A kidney drops in on “kidney”.",
 "Two kidneys holding hands. NOT FOR SALE lands on “attached”.",
 "The marketing-budget tower, then the chair and ≠ on “Not for a mom with a chair”.",
 "You at the desk at night. Hearts rise from Mom’s chair photo on “from her”.",
 "You smile. 10TH GRADE lands on “sophomore”.",
 "ALGEBRA book, then the monitor flips to CHURN on “customer churn”. HOMEWORK STILL DUE on “still due”.",
 "Client health: Marcus slips to AT RISK, the “we miss you” text goes out, he books. Leave the 1.6 s pause after this line: it’s the reply landing.",
 "Logo flash on “Message Health”, then MESSAGE + HEALTH.",
 "Heartbeat. BOOKS / LAST VISIT / REPLIES pop on each phrase.",
 "The line flattens. NO BEEP on “hospital beep”, then “just silence.”",
 "“We miss you!” goes out and the heartbeat comes back. The old ad gets crossed out on “beats any ad”.",
 "The salon tile appears.",
 "A tile pops for each business. The pipe starts dripping on “leak”.",
 "Customers walk away. NO GOODBYE, then RUDE. on “Rude, honestly”.",
 "2026, then the OPEN sign on “I opened it”.",
 "Mom, then you step in beside her on “hardworking owner”. Your hand goes to your heart on “single client”.",
 "Logo + the business tiles. YES, EVEN THE PLUMBERS. on “made for you too”.",
 "End card: logo, Try MsgHealth button, msghealth.net.",
]
assert len(beats) == len(clips) == len(at) == len(say)
def ts(x): m = int(x // 60); return f"{m}:{x - m * 60:04.1f}"
total = at[-1] + clips[-1][0] + 1.9
o = ["# MsgHealth “Our story”: voiceover script & timeline\n",
 f"Video: `dist/msghealth-story-9x16.mp4` (no voice, no captions) and `dist/msghealth-story-captions-9x16.mp4` (no voice, captions on). Runtime **{ts(total)}**, 1080×1920, 30 fps.\n",
 "The animation is cut to these times. Start each line at its **Start** time and finish it before the next line starts. A few tenths of a second early or late is fine; the beats on the right are the moments worth hitting exactly.\n",
 "## How to record it\n",
 "- **Easiest:** play `msghealth-story-captions-9x16.mp4` with headphones on and read the captions as they pop up. They’re timed to this script. Record in one take, then lay your audio on the clean video starting at **0:00.0**.",
 "- **Line by line:** record each line separately and drop it on the timeline at its Start time.",
 "- Pace is relaxed and conversational, about 2.5 words a second. The ↳ times inside a line are when each phrase should start.",
 "- The music sits low throughout so your voice can go on top without extra ducking. If you add your own captions, use the clean version.\n",
 "## Timeline\n", "| # | Start | End | Say | What’s on screen |", "|---|---|---|---|---|"]
for i, (d, ch) in enumerate(clips):
    s0 = at[i]
    sub = ' '.join(f"↳ *{ts(s0 + off)}* {c.replace('*', '')}" for c, off in ch[1:])
    o.append(f"| {i + 1} | **{ts(s0)}** | {ts(s0 + d)} | {say[i]}" + (f"<br><sub>{sub}</sub>" if sub else '') + f" | {beats[i]} |")
o += ["", "## Plain script (for a teleprompter)\n"] + [f"**{ts(at[i])}**  {say[i]}\n" for i in range(len(clips))]
o.append("---\nGenerated by `python3 scripts/story-script.py` from `src/story-vo.js`, the same timeline that drives the animation. To change a line, edit `scripts/vo/story.json`, regenerate the timeline (`python3 scripts/ads-vo.py story <kokoro.onnx> <voices.bin>`), re-render (`npm run render:story` and `npm run render:story:captions`), then run this script again.\n")
open('STORY-SCRIPT.md', 'w').write('\n'.join(o))
print('STORY-SCRIPT.md written,', len(clips), 'lines,', ts(total))

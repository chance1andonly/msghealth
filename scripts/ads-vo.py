# Builds the voiceover for one ad from scripts/vo/<name>.json with Kokoro TTS, then aligns the caption chunks.
#   python3 scripts/ads-vo.py NAME MODEL.onnx VOICES.bin
# Spec: { "voice": "am_michael", "speed": 1.08, "start": 0.3, "lines": [ { "say": "spoken text", "caps": ["chunk", ...], "gap": 0.25 } ] }
# "say" is what is read ("Message Health" for MsgHealth); "caps" are the on-screen caption chunks (*word* = accent).
# Writes assets/audio/NAME/vo-NN.wav (silence trimmed) and src/NAME-vo.js (VO_CLIPS, VO_AT, VO_TEXT).
import sys, json, re, os, numpy as np, soundfile as sf
from kokoro_onnx import Kokoro
name, model, voices = sys.argv[1:4]
spec = json.load(open(f'scripts/vo/{name}.json'))
os.makedirs(f'assets/audio/{name}', exist_ok=True)
k = Kokoro(model, voices)
def syl(s):
    s = s.lower().replace('*', '')
    for a, b in {'msghealth.net': 'mes sage health dot net', 'msghealth': 'mes sage health', 'fifty-one': 'fif ty one'}.items(): s = s.replace(a, b)
    n = 0
    for w in re.findall(r"[a-z']+", s):
        g = len(re.findall(r'[aeiouy]+', w))
        if w.endswith('e') and not w.endswith(('le', 'ee')) and g > 1: g -= 1
        n += max(1, g)
    return n
clips, at, t = [], [], spec.get('start', 0.3)
for i, ln in enumerate(spec['lines']):
    x, sr = k.create(ln['say'], voice=spec['voice'], speed=spec['speed'], lang='en-us')
    hop = int(sr * 0.005); e = np.array([np.sqrt((x[j:j + hop] ** 2).mean()) for j in range(0, len(x) - hop, hop)])
    v = np.where(e > e.max() * 0.04)[0]; a = max(0, (v[0] - 4) * hop); b = min(len(x), (v[-1] + 14) * hop)
    x = x[a:b]; sf.write(f'assets/audio/{name}/vo-{i:02d}.wav', x, sr)
    hop = int(sr * 0.01); e = np.array([np.sqrt((x[j:j + hop] ** 2).mean()) for j in range(0, len(x) - hop, hop)])
    v = np.where(e > e.max() * 0.06)[0]; s0, s1 = v[0], v[-1]
    sm = np.convolve(e, np.ones(5) / 5, 'same'); syls = [syl(c) for c in ln['caps']]; tot = sum(syls); acc = 0; starts = [0.0]
    for s in syls[:-1]:
        acc += s; f = int(s0 + (s1 - s0) * acc / tot); lo, hi = max(s0, f - 18), min(s1, f + 18)
        starts.append(round((lo + int(np.argmin(sm[lo:hi]))) * 0.01 + 0.03, 2))
    dur = round(len(x) / sr, 3); clips.append({'dur': dur, 'chunks': [[c, s] for c, s in zip(ln['caps'], starts)]})
    at.append(round(t, 2)); t += dur + ln.get('gap', 0.22)
rows = ['  ' + json.dumps(o, ensure_ascii=False).replace('{"dur"', '{ dur').replace('"chunks"', 'chunks').replace('}', ' }') + f', // {i:02d}' for i, o in enumerate(clips)]
js = f"// Generated by scripts/ads-vo.py from scripts/vo/{name}.json (Kokoro TTS, voice {spec['voice']}, speed {spec['speed']}): clip lengths,\n// caption chunk start times and when each clip starts. Don't edit by hand.\n"
js += 'window.VO_CLIPS = [\n' + '\n'.join(rows) + '\n];\n'
js += 'window.VO_AT = ' + json.dumps(at) + ';\n'
js += 'window.VO_TEXT = ' + json.dumps([l['say'] for l in spec['lines']], ensure_ascii=False) + ';\n'
open(f'src/{name}-vo.js', 'w').write(js); print(name, 'voice ends at', round(t, 2))

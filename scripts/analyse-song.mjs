// Measures the music bed so the picture can move with it: the 808/kick hits (time + strength) and smoothed
// low/high-band envelopes, sampled at 120 Hz over the 33 s window the film uses.
//   node scripts/analyse-song.mjs        → src/launch-music.js  (committed; derived data only, no audio)
// Env: SONG (default assets/audio/song.mp3), FFMPEG.
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
import '../src/launch-timing.js';

const TM = globalThis.TIMING, SR = 48000, RATE = 120;
const raw = execFileSync(process.env.FFMPEG || 'ffmpeg', ['-v', 'error', '-i', process.env.SONG || 'assets/audio/song.mp3', '-ss', String(TM.SONG_START), '-t', String(TM.DURATION), '-ar', String(SR), '-ac', '1', '-f', 'f32le', '-'], { maxBuffer: 1 << 28 });
const x = new Float32Array(raw.buffer, raw.byteOffset, Math.floor(raw.byteLength / 4));
function biquad(src, type, f, q = 0.707) {
  const w = 2 * Math.PI * f / SR, a = Math.sin(w) / (2 * q), c = Math.cos(w);
  const [b0, b1, b2] = type === 'lp' ? [(1 - c) / 2, 1 - c, (1 - c) / 2] : [(1 + c) / 2, -(1 + c), (1 + c) / 2];
  const a0 = 1 + a, a1 = -2 * c, a2 = 1 - a, y = new Float32Array(src.length);
  let x1 = 0, x2 = 0, y1 = 0, y2 = 0;
  for (let n = 0; n < src.length; n++) { const v = (b0 * src[n] + b1 * x1 + b2 * x2 - a1 * y1 - a2 * y2) / a0; x2 = x1; x1 = src[n]; y2 = y1; y1 = v; y[n] = v; }
  return y;
}
const env = (sig) => { const hop = SR / RATE, n = Math.floor(sig.length / hop), e = new Float32Array(n); for (let i = 0; i < n; i++) { let s = 0; for (let k = 0; k < hop; k++) s += sig[i * hop + k] ** 2; e[i] = Math.sqrt(s / hop); } return e; };
const lo = env(biquad(biquad(x, 'lp', 140), 'lp', 140)), hi = env(biquad(biquad(x, 'hp', 5000), 'hp', 5000));
const norm = (e) => { const s = [...e].sort((a, b) => a - b), top = s[Math.floor(s.length * 0.98)] || 1; return e.map((v) => Math.min(1, v / top)); };
const L = norm(lo), Hh = norm(hi);
// kicks: sharp rises of the low-band envelope
const kicks = []; let last = -1;
for (let i = 2; i < L.length - 3; i++) {
  // a rise of the low band in dB (an 808 that is already ringing still shows a sharp jump when it retriggers)
  const rise = 20 * Math.log10((lo[i + 2] + 1e-5) / (lo[i - 2] + 1e-5));
  if (rise > 4.5 && L[i + 2] > 0.12 && L[i + 2] >= L[i + 1] && (i - last) / RATE > 0.14) {
    let pk = 0; for (let k = i; k < i + 12 && k < L.length; k++) pk = Math.max(pk, L[k]);
    kicks.push([+(i / RATE).toFixed(3), +Math.min(1, pk).toFixed(2)]); last = i;
  }
}
// percussion: the sharp high-band clicks that carry the beat between the 808 hits
const hits = []; last = -1;
for (let i = 2; i < Hh.length - 3; i++) {
  const rise = 20 * Math.log10((hi[i + 1] + 1e-6) / (hi[i - 2] + 1e-6));
  if (rise > 9 && Hh[i + 1] > 0.25 && Hh[i + 1] >= Hh[i] && (i - last) / RATE > 0.12) {
    let pk = 0; for (let k = i; k < i + 6 && k < Hh.length; k++) pk = Math.max(pk, Hh[k]);
    hits.push([+(i / RATE).toFixed(3), +Math.min(1, pk).toFixed(2)]); last = i;
  }
}
const smooth = (e, a) => { const o = new Float32Array(e.length); let v = 0; for (let i = 0; i < e.length; i++) { v += (e[i] - v) * (e[i] > v ? 0.5 : a); o[i] = v; } return o; };
const q = (e) => Array.from(e, (v) => Math.round(v * 100));
fs.writeFileSync('src/launch-music.js', `// Generated by scripts/analyse-song.mjs — kick hits and band envelopes of the music bed (film time, 120 Hz, 0–100).\nglobalThis.MUSIC = ${JSON.stringify({ rate: RATE, kicks, hits, low: q(smooth(L, 0.08)), hi: q(smooth(Hh, 0.2)) })};\n`);
console.log('kicks', kicks.length, kicks.slice(0, 30).map((k) => k.join('@')).join(' '));
console.log('hits', hits.length, hits.slice(0, 40).map((k) => k.join('@')).join(' '));
